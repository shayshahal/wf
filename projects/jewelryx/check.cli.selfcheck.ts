// Optional affected checks through the real CLI, with a faithful uv process on PATH.
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { delimiter, join } from 'node:path';
import { WF_ROOT } from '../../src/paths.ts';
import { WF_STATE_VERSION } from '../../src/round/state.ts';

const root = mkdtempSync(join(tmpdir(), 'wf-affected-check-'));
const repo = join(root, 'repo');
const bin = join(root, 'bin');
const calls = join(root, 'calls');
const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')));
const git = (...args: string[]) => execFileSync('git', args, { cwd: repo, env, encoding: 'utf8', stdio: 'pipe' });
const cli = (args: string[] = [], extra: Record<string, string> = {}) => spawnSync(process.execPath, [join(WF_ROOT, 'wf.mjs'), 'check', ...args], { cwd: repo, env: { ...env, PATH: `${bin}${delimiter}${env.PATH}`, ...extra }, encoding: 'utf8', timeout: 120_000 });
const logs = () => readFileSync(join(repo, '.wf', 'checks.log'), 'utf8').trim().split('\n').map((line) => JSON.parse(line));
try {
 mkdirSync(join(repo, 'packages/backend/tests'), { recursive: true });
 mkdirSync(join(repo, '.wf')); mkdirSync(bin);
 writeFileSync(join(repo, '.gitignore'), '.wf/\n');
 writeFileSync(join(repo, 'packages/backend/tests/test_bug.py'), '# baseline\n');
 git('init', '-q', '-b', 'dev');
 git('-c', 'user.name=wf', '-c', 'user.email=wf@selfcheck', 'add', '.');
 git('-c', 'user.name=wf', '-c', 'user.email=wf@selfcheck', 'commit', '-qm', 'base');
 git('switch', '-qc', 'bench/affected');
 writeFileSync(join(repo, '.wf/state.json'), JSON.stringify({ wf_version: WF_STATE_VERSION, id: 'X-1', folder: 'bug-reports/X-1', class: 'A', step: 'build', base: 'dev' }));
 writeFileSync(join(bin, 'stub.cjs'), `const fs=require('node:fs');fs.appendFileSync(${JSON.stringify(calls)},JSON.stringify(process.argv.slice(2))+'\\n');if(process.env.WF_STUB_MUTATE)fs.appendFileSync('tests/test_bug.py','# rewritten\\n');console.log('observed output');process.exitCode=Number(process.env.WF_STUB_EXIT||0);`);
 writeFileSync(join(bin, process.platform === 'win32' ? 'uv.cmd' : 'uv'), process.platform === 'win32' ? '@node "%~dp0stub.cjs" %*\r\n' : '#!/bin/sh\nexec node "$(dirname "$0")/stub.cjs" "$@"\n', { mode: 0o755 });
 const empty = cli();
 assert.equal(empty.status, 0, empty.stdout + empty.stderr);
 assert(!existsSync(calls)); assert(!existsSync(join(repo, '.wf/checks.log')), 'no tasks is not a measured green');
 writeFileSync(join(repo, 'packages/backend/tests/test_bug.py'), '# changed\n');
 const green = cli();
 assert.equal(green.status, 0, green.stdout + green.stderr);
 const measured = logs().at(-1);
 assert.equal(measured.result, 'green'); assert.equal(measured.row, null);
 assert.equal(measured.tasks.length, 3);
 assert(measured.tasks.every((task: { output: string; durationMs: number }) => task.output.includes('observed output') && task.durationMs >= 0));
 const commands = readFileSync(calls, 'utf8').trim().split('\n').map((line) => JSON.parse(line));
 assert.deepEqual(commands.at(-1), ['run', '--frozen', 'pytest', 'tests/test_bug.py']);
 assert(!commands.some((args: string[]) => args.some((arg) => arg.includes('::'))), 'no selected assertion or baseline replay');
 const red = cli([], { WF_STUB_EXIT: '17' });
 assert.equal(red.status, 1, red.stdout + red.stderr);
 assert.equal(logs().at(-1).tasks[0].exit, 17);
 const mutation = cli([], { WF_STUB_MUTATE: '1' });
 assert.equal(mutation.status, 1, mutation.stdout + mutation.stderr);
 assert.equal(logs().at(-1).result, 'changed');
 const invalid = cli(['--case', '1']);
 assert.equal(invalid.status, 1); assert.match(invalid.stderr, /take no arguments/);
 const before = readFileSync(calls, 'utf8');
 git('switch', '-qc', 'fix/protected');
 mkdirSync(join(repo, 'verification'));
 writeFileSync(join(repo, 'verification/new.spec.ts'), '// protected\n');
 const protectedRun = cli();
 assert.equal(protectedRun.status, 1, protectedRun.stdout + protectedRun.stderr);
 assert.match(protectedRun.stderr, /protected oracle files/);
 assert.equal(readFileSync(calls, 'utf8'), before, 'protected files refuse before execution');
 console.log('optional affected checks: no empty green, observed exit/output/duration, mutation refusal and protected files');
} finally { rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); }
